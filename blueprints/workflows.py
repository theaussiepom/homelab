#!/usr/bin/env python3
"""Generate the stack's checked-in workflow graph from current declarative inputs."""

import argparse
import copy
import hashlib
import json
from pathlib import Path
import re
import sys
import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
import compile as compiler
import component_workflows
from component_input_secrets import SLOTS, PREFIX

HEADER = "# Generated by homelab/blueprints/workflows.py; edit blueprint/stack definitions.\n"
PHASE_RECIPE = Path(__file__).resolve().parents[1] / ".github/workflows/guest-phase.yml"
SHARED_SETUP_SHA256 = "d2729bb32bdd35e2766d5ff0373094e24aa4cc3207b1c77942f57bf4ff35e5b6"
MAX_JOB_MINUTES = 360
SETUP_NAMES = ("Check readiness", "Get settings", "Choose services", "Get services", "Choose tools", "Get tools", "Prepare tools")
INPUTS = ("disabled", "runner_labels", "environment_name")
COMMON_SECRETS = {"APPLICATION_SSH_KEY": True, "PROXMOX_APP_TOKEN": True}
SCALAR_SLOTS = tuple(sorted(slot for roles in SLOTS.values() for slot in roles.values()))
PRIVATE_MAIN = "github.event.repository.private == true && github.event_name == 'push' && github.ref == 'refs/heads/main'"


def secret_declarations(names=None):
    """The leaf admits finite slots; actual guest calls declare selected aliases."""
    selected = SCALAR_SLOTS if names is None else names
    compiler.require(isinstance(selected, (tuple, list)) and
                     all(isinstance(name, str) and re.fullmatch(r'[A-Za-z_][A-Za-z0-9_]*', name)
                         for name in selected) and len(selected) == len(set(selected)),
                     'Use explicit named scalar workflow secrets')
    return {**{name: {'required': True} for name in COMMON_SECRETS},
            **{name: {'required': names is not None} for name in selected}}


def secret_forwarding(names=None):
    return {name: '${{ secrets.' + name + ' }}' for name in secret_declarations(names)}


def workflow_call(names=None, *, phase=False):
    result = {'workflow_call': {'inputs': {
        name: ({'type': 'string', 'required': False, 'default': '[]'} if name == 'disabled'
               else {'type': 'string', 'required': True}) for name in INPUTS},
        'secrets': secret_declarations(names)}}
    if phase:
        result['workflow_call']['inputs'].update({name: {'type': 'string', 'required': True}
                                                  for name in ('guest', 'phase')})
    return result


def arguments():
    return {name: "${{ inputs." + name + " }}" for name in INPUTS}


def label(value):
    return component_workflows.label(value)


def phase_recipe(*, check_actions=True):
    """Read the selected checkout's leaf, refusing unsupported policy or context."""
    compiler.require(PHASE_RECIPE.is_file() and not PHASE_RECIPE.is_symlink(),
                     "Keep a regular authoritative framework phase recipe")
    document = yaml.safe_load(PHASE_RECIPE.read_text())
    compiler.require(isinstance(document, dict), "Use a complete framework phase recipe")
    if True in document:
        compiler.require("on" not in document, "Keep one framework workflow trigger")
        document["on"] = document.pop(True)
    compiler.require(set(document) == {"name", "on", "permissions", "defaults", "jobs"}
                     and document["on"] == workflow_call(phase=True)
                     and document["permissions"] == {"contents": "read"}
                     and document["defaults"] == {"run": {"shell": "bash"}}
                     and isinstance(document["jobs"], dict) and set(document["jobs"]) == {"run"},
                     "Review unsupported framework recipe policies before materialization")
    job = document["jobs"]["run"]
    policy = {
        "if": PRIVATE_MAIN + " && !contains(fromJSON(inputs.disabled || '[]'), inputs.guest)",
        "environment": "${{ inputs.environment_name }}",
        "runs-on": "${{ fromJSON(inputs.runner_labels) }}",
        "timeout-minutes": 45,
        "env": {"HOMELAB_DEPLOYMENT_WORKFLOW": "${{ github.workflow_ref }}"},
    }
    compiler.require(isinstance(job, dict) and set(job) == {*policy, "name", "steps"}
                     and all(job[key] == value for key, value in policy.items())
                     and isinstance(job["steps"], list) and len(job["steps"]) == 10,
                     "Preserve the existing phase job policies and ten steps")
    step_keys = [
        {"name", "run"}, {"uses", "with"}, {"name", "id", "run"},
        {"uses", "with"}, {"name", "id", "run"}, {"uses", "with"},
        {"name", "run"}, {"name", "env", "run"}, {"name", "env", "run"}, {"name", "env", "run"},
    ]
    step_env = {
        7: {"GUEST", "PHASE", "DISABLED"},
        8: {"GUEST", "PHASE", *COMMON_SECRETS},
        9: {"GUEST", "PHASE", *(PREFIX + slot.upper() for slot in SCALAR_SLOTS)},
    }
    for index, step in enumerate(job["steps"]):
        compiler.require(isinstance(step, dict) and set(step) == step_keys[index]
                         and isinstance(step.get("env", {}), dict)
                         and set(step.get("env", {})) == step_env.get(index, set()),
                         "Review unsupported phase step fields or credential scope")
        if "run" in step:
            compiler.require(isinstance(step["run"], str) and "${{" not in step["run"],
                             "Keep phase command bytes independent of workflow input expressions")
        else:
            compiler.require(isinstance(step["uses"], str)
                             and re.fullmatch(r"actions/checkout@[0-9a-f]{40}", step["uses"])
                             and isinstance(step["with"], dict)
                             and step["with"].get("persist-credentials") is False,
                             "Preserve immutable checkout actions without persisted credentials")
    text = json.dumps(document)
    compiler.require(not any(token in text for token in ("github.job", "GITHUB_JOB", "job_workflow_ref")),
                     "Review job-identity dependencies before changing workflow nesting")
    allowed = {"inputs." + key for key in (*INPUTS, "guest", "phase")}
    allowed |= {"secrets." + key for key in secret_declarations()}
    allowed |= {"github.event.repository.private", "github.event_name", "github.ref", "github.workflow_ref"}
    allowed |= {"steps." + step + ".outputs." + field for step in ("stack", "framework") for field in ("repository", "revision")}
    texts, pending = [], [job]
    while pending:
        value = pending.pop()
        if isinstance(value, dict):
            pending.extend(item for key, item in value.items() if key != "run")
        elif isinstance(value, list):
            pending.extend(value)
        elif isinstance(value, str):
            texts.append(value)
    expressions = "\n".join(texts)
    references = re.findall(r"\b(?:inputs|secrets|github|steps|needs|matrix|strategy|env|vars|runner|job)(?:\.[A-Za-z0-9_]+)*\b", expressions)
    compiler.require(set(references) <= allowed and not re.search(r"\b(?:inputs|secrets|github|steps)(?:\.[A-Za-z0-9_]+)*\s*\[", expressions),
                     "Review unsupported workflow context dependencies")
    compiler.require(hashlib.sha256(json.dumps(job["steps"][:7], sort_keys=True).encode()).hexdigest()
                     == SHARED_SETUP_SHA256,
                     "Review changed common setup before sharing it across guest phases")
    if check_actions:
        for name, expected in composite_actions(job).items():
            path = PHASE_RECIPE.parents[1] / 'actions' / name / 'action.yml'
            compiler.require(path.is_file() and not path.is_symlink()
                             and yaml.safe_load(path.read_text()) == expected,
                             'Keep shared actions identical to the authoritative phase recipe')
    return job, document["defaults"]


def composite_actions(recipe):
    """Presentation wrappers retain the leaf's separate credential environments."""
    setup = copy.deepcopy(recipe['steps'][:7])
    for step, name in zip(setup, SETUP_NAMES):
        step['name'] = name
        if 'run' in step:
            step['shell'] = 'bash'
    steps = [copy.deepcopy(recipe['steps'][0]), *copy.deepcopy(recipe['steps'][7:])]
    for step, name in zip(steps, ('Check readiness', 'Check inputs', 'Load credentials', 'Deploy')):
        step.update(name=name, shell='bash')
        if 'env' in step:
            step['env'] = {key: value.replace('secrets.', 'inputs.')
                           for key, value in step['env'].items()}
    inputs = {name: {'description': 'Selected ' + name, 'required': name != 'disabled',
                     **({'default': '[]'} if name == 'disabled' else {})}
              for name in ('guest', 'phase', 'disabled')}
    inputs.update({name: {'description': 'Existing scoped credential', 'required': row['required']}
                   for name, row in secret_declarations().items()})
    return {
        'guest-setup': {'name': 'Setup', 'description': 'Select immutable settings, services and tools',
                        'runs': {'using': 'composite', 'steps': setup}},
        'guest-phase': {'name': 'Guest phase', 'description': 'Run one guarded admitted deployment phase',
                        'inputs': inputs, 'runs': {'using': 'composite', 'steps': steps}},
    }


