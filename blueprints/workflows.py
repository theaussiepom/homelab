#!/usr/bin/env python3
"""Generate the stack's checked-in workflow graph from current declarative inputs."""

import argparse
import json
from pathlib import Path
import re
import sys
import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
import compile as compiler

HEADER = "# Generated by homelab/blueprints/workflows.py; edit blueprint/stack definitions.\n"
INPUTS = ("disabled", "runner_labels", "environment_name")
PRIVATE_MAIN = "github.event.repository.private == true && github.event_name == 'push' && github.ref == 'refs/heads/main'"


def workflow_call():
    return {
        "workflow_call": {
            "inputs": {
                name: (
                    {"type": "string", "required": False, "default": "[]"}
                    if name == "disabled"
                    else {"type": "string", "required": True}
                )
                for name in INPUTS
            }
        }
    }


def arguments():
    return {name: "${{ inputs." + name + " }}" for name in INPUTS}


def label(value):
    compiler.require(
        isinstance(value, str)
        and value.strip()
        and not any(c in value for c in "\r\n\x00"),
        "Supply a single-line workflow display name",
    )
    return value


def models(stack):
    """Return complete workflow documents; no credentials, target access or writes."""
    spec = compiler.manifest(stack)
    deploy = {
        "name": "HomeLab stack",
        "on": workflow_call(),
        "permissions": {"contents": "read"},
        "jobs": {
            "selection": {
                "name": "Validate guest selection",
                "if": PRIVATE_MAIN,
                "runs-on": "ubuntu-24.04",
                "timeout-minutes": 2,
                "steps": [{
                    "name": "Reject invalid exclusions before the guest graph",
                    "env": {
                        "DISABLED": "${{ inputs.disabled }}",
                        "DEPENDENCIES": json.dumps({name: row["depends_on"] for name, row in spec["guests"].items()}),
                    },
                    "run": """python3 - <<'PYCODE'
import json, os
spec = json.loads(os.environ['DEPENDENCIES'])
disabled = json.loads(os.environ['DISABLED'] or '[]')
if not (isinstance(disabled, list) and all(isinstance(name, str) for name in disabled)
        and len(set(disabled)) == len(disabled) and set(disabled) <= set(spec)):
    raise SystemExit('Disable only unique known guest names')
active = set(spec) - set(disabled)
if any(not set(spec[name]) <= active for name in active):
    raise SystemExit('Cannot disable a prerequisite while its consumers remain active')
PYCODE
""",
                }],
            },
        },
    }
    result = {"deploy.yml": deploy}
    for guest, blueprint in compiler.CATALOGUE.items():
        compiler.require(
            re.fullmatch(r"[a-z][a-z0-9-]*", guest) and guest != "selection",
            "Use a safe guest workflow identifier",
        )
        compiler.require(
            isinstance(blueprint, dict)
            and {"name", "applications", "application_names"} <= blueprint.keys(),
            "Define workflow names in the current blueprint metadata",
        )
        apps = blueprint["applications"]
        names = blueprint["application_names"]
        compiler.require(
            isinstance(apps, list)
            and apps
            and all(
                isinstance(phase, str)
                and re.fullmatch(r"[a-z][a-z0-9_-]*", phase)
                and phase not in {"infrastructure", "preparation"}
                for phase in apps
            )
            and len(apps) == len(set(apps))
            and isinstance(names, dict)
            and set(names) == set(apps),
            "Label every current application phase exactly once",
        )
        guest_name = label(blueprint["name"])
        phases = {
            "infrastructure": "Infrastructure",
            "preparation": "Preparation",
            **{phase: label(names[phase]) for phase in apps},
        }
        parent = {"name": guest_name}
        needs = spec["guests"][guest]["depends_on"]
        parent["needs"] = ["selection", *needs]
        # GitHub conditions combine with &&, while workflow inputs remain literal
        # expression strings. No job identifier or dependency is decided at runtime.
        parent["if"] = (
            PRIVATE_MAIN
            + " && !contains(fromJSON(inputs.disabled || '[]'), '"
            + guest
            + "')"
        )
        parent.update(
            {
                "uses": "./.github/workflows/guest-" + guest + ".yml",
                "with": arguments(),
                "secrets": "inherit",
            }
        )
        deploy["jobs"][guest] = parent
        workflow = {
            "name": guest_name,
            "on": workflow_call(),
            "permissions": {"contents": "read"},
            "jobs": {},
        }
        previous = None
        for phase, display in phases.items():
            job = {"name": display}
            if previous:
                job["needs"] = previous
            job.update(
                {
                    "uses": "./.github/workflows/phase.yml",
                    "with": dict(arguments(), guest=guest, phase=phase),
                    "secrets": "inherit",
                }
            )
            workflow["jobs"][phase] = job
            previous = phase
        result["guest-" + guest + ".yml"] = workflow
    return result


def rendered(stack):
    return {
        name: (
            HEADER
            + yaml.safe_dump(document, sort_keys=False, width=1000, allow_unicode=True)
        ).encode()
        for name, document in models(stack).items()
    }


def synchronize(stack, *, check):
    """Write only owned workflow paths, or report drift without changing any file."""
    expected = rendered(stack)
    directory = stack / ".github/workflows"
    compiler.require(
        not (stack / ".github").is_symlink() and not directory.is_symlink(),
        "Use regular source directories for generated workflows",
    )
    existing = {
        p.name: p
        for pattern in ("guest-*.yml", "guest-*.yaml", "deploy.yml", "deploy.yaml")
        for p in directory.glob(pattern)
    }
    unexpected = sorted(set(existing) - set(expected))
    compiler.require(
        not unexpected,
        "Remove obsolete workflow paths explicitly: " + ", ".join(unexpected),
    )
    for path in existing.values():
        compiler.require(
            path.is_file() and not path.is_symlink(),
            "Generated workflow paths must be regular files",
        )
    changed = [
        name
        for name, raw in expected.items()
        if name not in existing or existing[name].read_bytes() != raw
    ]
    if check:
        compiler.require(
            not changed, "Generated workflows are stale: " + ", ".join(changed)
        )
    else:
        directory.mkdir(parents=True, exist_ok=True)
        for name in changed:
            (directory / name).write_bytes(expected[name])
    return {"workflows": len(expected), "changed": len(changed)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--stack", type=Path, required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        result = synchronize(args.stack, check=args.check)
    except (ValueError, KeyError) as exc:
        raise SystemExit(str(exc)) from None
    print(f"{result['workflows']} generated workflows; {result['changed']} changed.")


if __name__ == "__main__":
    main()
