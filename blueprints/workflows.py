#!/usr/bin/env python3
"""Generate the stack's checked-in workflow graph from current declarative inputs."""

import argparse
import copy
import json
from pathlib import Path
import re
import sys
import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
import compile as compiler

HEADER = "# Generated by homelab/blueprints/workflows.py; edit blueprint/stack definitions.\n"
PHASE_RECIPE = Path(__file__).resolve().parents[1] / ".github/workflows/guest-phase.yml"
INPUTS = ("disabled", "runner_labels", "environment_name")
COMMON_SECRETS = {"APPLICATION_SSH_KEY": True, "PROXMOX_APP_TOKEN": True}
APPLICATION_SECRETS = {
    "automation": {"AUTOMATION_NODE_RED_API_TOKEN": True},
    "identity": {
        "FOUNDATION_AUTHENTIK_POSTGRES_PASSWORD": True,
        "FOUNDATION_AUTHENTIK_SECRET_KEY": True,
        "FOUNDATION_AUTHENTIK_SMTP_PASSWORD": False,
    },
    "db-tools": {"FOUNDATION_PGADMIN_OAUTH_SECRET": True},
    "ingress": {"FOUNDATION_CLOUDFLARE_DNS_TOKEN": True},
}
PRIVATE_MAIN = "github.event.repository.private == true && github.event_name == 'push' && github.ref == 'refs/heads/main'"


def secret_declarations(guest=None):
    """Generic wrappers admit named subsets; each guest declares its own needs."""
    applications = (
        {name: False for values in APPLICATION_SECRETS.values() for name in values}
        if guest is None else APPLICATION_SECRETS.get(guest, {})
    )
    return {name: {"required": required} for name, required in {**COMMON_SECRETS, **applications}.items()}


def secret_forwarding(guest=None):
    """Forward existing names explicitly; never rely on inherited secret context."""
    return {name: "${{ secrets." + name + " }}" for name in secret_declarations(guest)}


def workflow_call(guest=None, *, phase=False):
    result = {
        "workflow_call": {
            "inputs": {
                name: (
                    {"type": "string", "required": False, "default": "[]"}
                    if name == "disabled"
                    else {"type": "string", "required": True}
                )
                for name in INPUTS
            }
        }
    }
    result["workflow_call"]["secrets"] = secret_declarations(guest)
    if phase:
        result["workflow_call"]["inputs"].update({name: {"type": "string", "required": True} for name in ("guest", "phase")})
    return result


def arguments():
    return {name: "${{ inputs." + name + " }}" for name in INPUTS}


def label(value):
    compiler.require(
        isinstance(value, str)
        and value.strip()
        and not any(c in value for c in "\r\n\x00"),
        "Supply a single-line workflow display name",
    )
    return value


def phase_recipe():
    """Read the selected checkout's leaf, refusing unsupported policy or context."""
    compiler.require(PHASE_RECIPE.is_file() and not PHASE_RECIPE.is_symlink(),
                     "Keep a regular authoritative framework phase recipe")
    document = yaml.safe_load(PHASE_RECIPE.read_text())
    compiler.require(isinstance(document, dict), "Use a complete framework phase recipe")
    if True in document:
        compiler.require("on" not in document, "Keep one framework workflow trigger")
        document["on"] = document.pop(True)
    compiler.require(set(document) == {"name", "on", "permissions", "defaults", "jobs"}
                     and document["on"] == workflow_call(phase=True)
                     and document["permissions"] == {"contents": "read"}
                     and document["defaults"] == {"run": {"shell": "bash"}}
                     and isinstance(document["jobs"], dict) and set(document["jobs"]) == {"run"},
                     "Review unsupported framework recipe policies before materialization")
    job = document["jobs"]["run"]
    policy = {
        "if": PRIVATE_MAIN + " && !contains(fromJSON(inputs.disabled || '[]'), inputs.guest)",
        "environment": "${{ inputs.environment_name }}",
        "runs-on": "${{ fromJSON(inputs.runner_labels) }}",
        "timeout-minutes": 45,
        "env": {"HOMELAB_DEPLOYMENT_WORKFLOW": "${{ github.workflow_ref }}"},
    }
    compiler.require(isinstance(job, dict) and set(job) == {*policy, "name", "steps"}
                     and all(job[key] == value for key, value in policy.items())
                     and isinstance(job["steps"], list) and len(job["steps"]) == 9,
                     "Preserve the existing phase job policies and nine steps")
    step_keys = [
        {"name", "run"}, {"uses", "with"}, {"name", "id", "run"},
        {"uses", "with"}, {"name", "id", "run"}, {"uses", "with"},
        {"name", "env", "run"}, {"name", "env", "run"}, {"name", "env", "run"},
    ]
    step_env = {
        6: {"GUEST", "PHASE", "DISABLED"},
        7: {"GUEST", "PHASE", *COMMON_SECRETS},
        8: {"GUEST", "PHASE", "NODE_RED_API_TOKEN", "AUTHENTIK_SECRET_KEY",
            "AUTHENTIK_POSTGRES_PASSWORD", "AUTHENTIK_SMTP_PASSWORD",
            "PGADMIN_OAUTH_SECRET", "CLOUDFLARE_DNS_TOKEN"},
    }
    for index, step in enumerate(job["steps"]):
        compiler.require(isinstance(step, dict) and set(step) == step_keys[index]
                         and isinstance(step.get("env", {}), dict)
                         and set(step.get("env", {})) == step_env.get(index, set()),
                         "Review unsupported phase step fields or credential scope")
        if "run" in step:
            compiler.require(isinstance(step["run"], str) and "${{" not in step["run"],
                             "Keep phase command bytes independent of workflow input expressions")
        else:
            compiler.require(isinstance(step["uses"], str)
                             and re.fullmatch(r"actions/checkout@[0-9a-f]{40}", step["uses"])
                             and isinstance(step["with"], dict)
                             and step["with"].get("persist-credentials") is False,
                             "Preserve immutable checkout actions without persisted credentials")
    text = json.dumps(document)
    compiler.require(not any(token in text for token in ("github.job", "GITHUB_JOB", "job_workflow_ref")),
                     "Review job-identity dependencies before changing workflow nesting")
    allowed = {"inputs." + key for key in (*INPUTS, "guest", "phase")}
    allowed |= {"secrets." + key for key in secret_declarations()}
    allowed |= {"github.event.repository.private", "github.event_name", "github.ref", "github.workflow_ref"}
    allowed |= {"steps." + step + ".outputs." + field for step in ("stack", "framework") for field in ("repository", "revision")}
    texts, pending = [], [job]
    while pending:
        value = pending.pop()
        if isinstance(value, dict):
            pending.extend(item for key, item in value.items() if key != "run")
        elif isinstance(value, list):
            pending.extend(value)
        elif isinstance(value, str):
            texts.append(value)
    expressions = "\n".join(texts)
    references = re.findall(r"\b(?:inputs|secrets|github|steps|needs|matrix|strategy|env|vars|runner|job)(?:\.[A-Za-z0-9_]+)*\b", expressions)
    compiler.require(set(references) <= allowed and not re.search(r"\b(?:inputs|secrets|github|steps)(?:\.[A-Za-z0-9_]+)*\s*\[", expressions),
                     "Review unsupported workflow context dependencies")
    return job, document["defaults"]


def bind_phase(value, guest, phase):
    """Bind only known constants; copied command bodies remain byte-for-byte intact."""
    if isinstance(value, dict):
        return {key: item if key == "run" else bind_phase(item, guest, phase)
                for key, item in value.items()}
    if isinstance(value, list):
        return [bind_phase(item, guest, phase) for item in value]
    if not isinstance(value, str):
        return value
    guard = re.fullmatch(r"\$\{\{ inputs\.guest == '([a-z-]+)' && secrets\.([A-Z_]+) \|\| '' \}\}", value)
    if guard and guard[2] not in secret_declarations(guest):
        compiler.require(guest != guard[1], "Never replace a selected application credential")
        value = value.replace("secrets." + guard[2], "''")
    for name, constant in (("guest", guest), ("phase", phase)):
        value = value.replace("${{ inputs." + name + " }}", constant)
        value = re.sub(r"\binputs\." + name + r"\b", "'" + constant + "'", value)
    return value


def models(stack):
    """Return complete workflow documents; no credentials, target access or writes."""
    spec = compiler.manifest(stack)
    recipe, defaults = phase_recipe()
    deploy = {
        "name": "HomeLab stack",
        "on": workflow_call(),
        "permissions": {"contents": "read"},
        "jobs": {
            "selection": {
                "name": "Validate guest selection",
                "if": PRIVATE_MAIN,
                "runs-on": "ubuntu-24.04",
                "timeout-minutes": 2,
                "steps": [{
                    "name": "Reject invalid exclusions before the guest graph",
                    "env": {
                        "DISABLED": "${{ inputs.disabled }}",
                        "DEPENDENCIES": json.dumps({name: row["depends_on"] for name, row in spec["guests"].items()}),
                    },
                    "run": """python3 - <<'PYCODE'
import json, os
spec = json.loads(os.environ['DEPENDENCIES'])
disabled = json.loads(os.environ['DISABLED'] or '[]')
if not (isinstance(disabled, list) and all(isinstance(name, str) for name in disabled)
        and len(set(disabled)) == len(disabled) and set(disabled) <= set(spec)):
    raise SystemExit('Disable only unique known guest names')
active = set(spec) - set(disabled)
if any(not set(spec[name]) <= active for name in active):
    raise SystemExit('Cannot disable a prerequisite while its consumers remain active')
PYCODE
""",
                }],
            },
        },
    }
    result = {"deploy.yml": deploy}
    for guest, blueprint in compiler.CATALOGUE.items():
        compiler.require(
            re.fullmatch(r"[a-z][a-z0-9-]*", guest) and guest != "selection",
            "Use a safe guest workflow identifier",
        )
        compiler.require(
            isinstance(blueprint, dict)
            and {"name", "applications", "application_names"} <= blueprint.keys(),
            "Define workflow names in the current blueprint metadata",
        )
        apps = blueprint["applications"]
        names = blueprint["application_names"]
        compiler.require(
            isinstance(apps, list)
            and apps
            and all(
                isinstance(phase, str)
                and re.fullmatch(r"[a-z][a-z0-9_-]*", phase)
                and phase not in {"infrastructure", "preparation"}
                for phase in apps
            )
            and len(apps) == len(set(apps))
            and isinstance(names, dict)
            and set(names) == set(apps),
            "Label every current application phase exactly once",
        )
        guest_name = label(blueprint["name"])
        application_names = {phase: label(names[phase]) for phase in apps}
        phases = {
            "infrastructure": "Infra",
            "preparation": "Prepare",
            **{phase: "Deployment" if len(apps) == 1 else application_names[phase] for phase in apps},
        }
        parent = {"name": guest_name}
        needs = spec["guests"][guest]["depends_on"]
        parent["needs"] = ["selection", *needs]
        # GitHub conditions combine with &&, while workflow inputs remain literal
        # expression strings. No job identifier or dependency is decided at runtime.
        parent["if"] = (
            PRIVATE_MAIN
            + " && !contains(fromJSON(inputs.disabled || '[]'), '"
            + guest
            + "')"
        )
        parent.update(
            {
                "uses": "./.github/workflows/guest-" + guest + ".yml",
                "with": arguments(),
                "secrets": secret_forwarding(guest),
            }
        )
        deploy["jobs"][guest] = parent
        workflow = {
            "name": guest_name,
            "on": workflow_call(guest),
            "permissions": {"contents": "read"},
            "defaults": copy.deepcopy(defaults),
            "jobs": {},
        }
        previous = None
        for phase, display in phases.items():
            job = bind_phase(recipe, guest, phase)
            job["name"] = display
            job["steps"][-1]["name"] = "Deployment"
            if previous:
                job["needs"] = previous
            workflow["jobs"][phase] = job
            previous = phase
        result["guest-" + guest + ".yml"] = workflow
    selected = stack / ".github/workflows/phase.yml"
    compiler.require(selected.is_file() and not selected.is_symlink(), "Keep one regular selected framework phase workflow")
    framework = compiler.workflow_selection(selected, "guest-phase.yml")
    result["phase.yml"] = {
        "name": "Guest phase",
        "on": workflow_call(phase=True),
        "permissions": {"contents": "read"},
        "jobs": {"run": {
            "uses": framework["repository"] + "/.github/workflows/guest-phase.yml@" + framework["revision"],
            "with": dict(arguments(), guest="${{ inputs.guest }}", phase="${{ inputs.phase }}"),
            "secrets": secret_forwarding(),
        }},
    }
    return result


def rendered(stack):
    return {
        name: (
            HEADER
            + yaml.safe_dump(document, sort_keys=False, width=1000, allow_unicode=True)
        ).encode()
        for name, document in models(stack).items()
    }


def synchronize(stack, *, check):
    """Write only owned workflow paths, or report drift without changing any file."""
    expected = rendered(stack)
    directory = stack / ".github/workflows"
    compiler.require(
        not (stack / ".github").is_symlink() and not directory.is_symlink(),
        "Use regular source directories for generated workflows",
    )
    existing = {
        p.name: p
        for pattern in ("guest-*.yml", "guest-*.yaml", "deploy.yml", "deploy.yaml", "phase.yml", "phase.yaml")
        for p in directory.glob(pattern)
    }
    unexpected = sorted(set(existing) - set(expected))
    compiler.require(
        not unexpected,
        "Remove obsolete workflow paths explicitly: " + ", ".join(unexpected),
    )
    for path in existing.values():
        compiler.require(
            path.is_file() and not path.is_symlink(),
            "Generated workflow paths must be regular files",
        )
    changed = [
        name
        for name, raw in expected.items()
        if name not in existing or existing[name].read_bytes() != raw
    ]
    if check:
        compiler.require(
            not changed, "Generated workflows are stale: " + ", ".join(changed)
        )
    else:
        directory.mkdir(parents=True, exist_ok=True)
        for name in changed:
            (directory / name).write_bytes(expected[name])
    return {"workflows": len(expected), "changed": len(changed)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--stack", type=Path, required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        result = synchronize(args.stack, check=args.check)
    except (ValueError, KeyError) as exc:
        raise SystemExit(str(exc)) from None
    print(f"{result['workflows']} generated workflows; {result['changed']} changed.")


if __name__ == "__main__":
    main()
