#!/usr/bin/env python3
"""Materialize the same pinned guest recipes as plain private native jobs.

Each job uses its own main-only Environment containing exactly its former
explicit secret subset. This module reads source only; it never handles values.
"""
import argparse
import copy
import json
from pathlib import Path
import re
import subprocess
import yaml

import compile as compiler
import workflows

HEADER = '# Generated by homelab/blueprints/private_workflows.py; edit source selections and regenerate.\n'
REQUIRED = {'HOMELAB_STACK_SOURCE', 'HOMELAB_ENVIRONMENT_PREFIX', 'HOMELAB_RUNNER_LABELS', 'HOMELAB_REPOSITORY'}
WORKFLOW_INPUTS = re.compile(r'\binputs(?:\s|\\[nrt])*(?:\.|\[)')
PBS_WORKFLOW = '.github/workflows/pbs-firewall.yml'
PBS_SECRET = 'PBS_FIREWALL_SSH_KEY'


def settings(site):
    path = site / '.github/workflows/deploy.yml'
    value = yaml.safe_load(path.read_text())
    compiler.require(isinstance(value, dict) and isinstance(value.get('env'), dict),
                     'Declare private workflow source settings')
    env = value['env']
    compiler.require(REQUIRED <= env.keys() <= REQUIRED | {'HOMELAB_DISABLED'}
                     and all(isinstance(v, str) and '${{' not in v and '\n' not in v for v in env.values()),
                     'Use literal closed private workflow settings')
    selected = compiler.workflow_selection(path, 'deploy.yml')
    compiler.require(env['HOMELAB_STACK_SOURCE'] == selected['repository'] + '/.github/workflows/deploy.yml@' + selected['revision'],
                     'Bind the declared immutable stack source')
    compiler.require(re.fullmatch(r'[a-z][a-z0-9-]{0,49}', env['HOMELAB_ENVIRONMENT_PREFIX'])
                     and re.fullmatch(r'[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+', env['HOMELAB_REPOSITORY']),
                     'Use bounded Environment and private repository names')
    labels = json.loads(env['HOMELAB_RUNNER_LABELS'])
    compiler.require(isinstance(labels, list) and labels and all(isinstance(v, str) and re.fullmatch(r'[A-Za-z0-9_-]+', v) for v in labels)
                     and len(labels) == len(set(labels)) and 'self-hosted' in labels,
                     'Preserve the declared private runner labels')
    return env, labels


def bind(value, disabled):
    if isinstance(value, dict):
        return {key: bind(item, disabled) for key, item in value.items()}
    if isinstance(value, list):
        return [bind(item, disabled) for item in value]
    return disabled if value == '${{ inputs.disabled }}' else value


def validation_workflow(site):
    path = site / '.github/workflows/ci.yml'
    compiler.require(path.is_file() and not path.is_symlink(), 'Use a reusable local CI workflow')
    value = yaml.safe_load(path.read_text())
    # PyYAML's YAML 1.1 loader reads an unquoted GitHub "on" key as True.
    events = value.get('on', value.get(True)) if isinstance(value, dict) else None
    events = [events] if isinstance(events, str) else events
    compiler.require(isinstance(events, (dict, list)) and 'workflow_call' in events,
                     'Use a reusable local CI workflow with workflow_call')
    compiler.require(isinstance(value.get('jobs'), dict) and bool(value['jobs']),
                     'Use a reusable local CI workflow containing jobs')
    compiler.require(set(value) <= {'name', 'on', True, 'permissions', 'jobs'}
                     and value.get('permissions', {'contents': 'read'}) == {'contents': 'read'},
                     'Preserve the source validation workflow context and read-only permissions')
    compiler.require(set(value['jobs']) == {'source'}
                     and isinstance(value['jobs']['source'], dict)
                     and isinstance(value['jobs']['source'].get('steps'), list),
                     'Use one native source validation job')
    job = copy.deepcopy(value['jobs']['source'])
    compiler.require(not WORKFLOW_INPUTS.search(json.dumps(job)),
                     'Materialize only closed validation job inputs')
    # A native job avoids GitHub's automatic caller/callee name separator.
    # Preserve the original Ubuntu default shell instead of inheriting Deploy's.
    job.update(name='Validate')
    job.setdefault('defaults', {'run': {'shell': 'bash -e {0}'}})
    return job


def pbs_workflow(site, labels):
    """Admit the one optional local PBS call contract, never interpret its steps."""
    path = site / PBS_WORKFLOW
    compiler.require(not any(p.is_symlink() for p in (path, path.parent, path.parent.parent)),
                     'Keep the local PBS workflow and its parents regular')
    if not path.exists():
        return False
    compiler.require(path.is_file(), 'Use a regular local PBS workflow')
    value = compiler.read(path)
    compiler.require(isinstance(value, dict) and set(value) <= {'name', 'on', True, 'permissions', 'jobs'}
                     and not ('on' in value and True in value)
                     and value.get('permissions') == {'contents': 'read'},
                     'Keep the closed read-only PBS workflow context')
    events = value.get('on', value.get(True))
    compiler.require(isinstance(events, dict) and set(events) == {'pull_request', 'workflow_call'}
                     and events['workflow_call'] == {'secrets': {PBS_SECRET: {'required': True}}}
                     and events['pull_request'] == {'paths': ['bootstrap/pbs-firewall.yaml',
                         'bootstrap/pbs-known_hosts', 'tests/fixtures/pbs-firewall.example.yaml', PBS_WORKFLOW]},
                     'Use only PBS PR validation and its one named reusable secret; no standalone writer')
    jobs = value.get('jobs')
    compiler.require(isinstance(jobs, dict) and set(jobs) == {'validate', 'firewall'}
                     and all(isinstance(job, dict) for job in jobs.values()),
                     'Keep exactly the PBS validation and native jobs')
    validation, native = jobs['validate'], jobs['firewall']
    # Keep Unicode whitespace visible and normalize JSON's escaped ASCII
    # whitespace. A quoted step ID such as "inputs" is not a context reference.
    context_end = r'\s*(?:\.|\[|(?=[),}\]|&=!<>]))'
    compiler.require(set(validation) <= {'name', 'runs-on', 'outputs', 'steps', 'timeout-minutes'}
                     and validation.get('runs-on') == 'ubuntu-24.04'
                     and validation.get('outputs') == {'selected': '${{ steps.selection.outputs.selected }}'}
                     and isinstance(validation.get('steps'), list)
                     and not re.search(r'\bsecrets' + context_end,
                         re.sub(r'\\(?:[nrtf]|u000b)', ' ', json.dumps(validation, ensure_ascii=False)), re.IGNORECASE),
                     'Keep PBS validation hosted and without protected credentials')
    compiler.require(set(native) <= {'name', 'needs', 'if', 'runs-on', 'environment', 'timeout-minutes', 'steps'}
                     and native.get('needs') == 'validate'
                     and native.get('if') == workflows.PRIVATE_MAIN + " && needs.validate.outputs.selected == 'true'"
                     and native.get('environment') == 'homelab-bootstrap'
                     and native.get('timeout-minutes') == 15
                     and isinstance(native.get('runs-on'), list)
                     and all(isinstance(label, str) for label in native['runs-on'])
                     and set(native['runs-on']) == set(labels)
                     and isinstance(native.get('steps'), list)
                     and not re.search(r'(?<![\w.])inputs' + context_end,
                         re.sub(r'\\(?:[nrtf]|u000b)', ' ', json.dumps(jobs, ensure_ascii=False)), re.IGNORECASE),
                     'Preserve selected protected PBS execution without a nested queue or unbound inputs')
    return value


def pbs_steps(value, framework):
    """Combine the existing pure check and native policy stages under shared setup."""
    validation, native = value['jobs']['validate'], value['jobs']['firewall']
    compiler.require(sum(step.get('id') == 'selection' for step in validation['steps']) == 1,
                     'Keep the explicit PBS policy selection step')
    result = []
    for label, job in (('check', validation), ('host', native)):
        ids = [step['id'] for step in job['steps'] if 'id' in step]
        compiler.require(all(isinstance(item, str) and re.fullmatch('[A-Za-z_][A-Za-z0-9_-]*', item) for item in ids)
                         and len(ids) == len(set(ids)), 'Keep unique literal PBS step identities')
        identities = {step['id']: 'pbs_' + label + '_' + step['id']
                      for step in job['steps'] if 'id' in step}
        def bind_steps(item):
            if isinstance(item, dict): return {key: bind_steps(row) for key, row in item.items()}
            compiler.require(not isinstance(item, list), 'Keep scalar PBS step inputs')
            if isinstance(item, str):
                for before, after in identities.items():
                    item = re.sub(r'\bsteps\.' + re.escape(before) + r'(?=\.)', 'steps.' + after, item)
            return item
        for original in job['steps']:
            step = copy.deepcopy(original)
            if 'uses' in step and step['uses'].startswith('actions/checkout@'):
                options = step.get('with', {})
                compiler.require(set(step) == {'uses', 'with'} and options.get('persist-credentials') is False,
                                 'Preserve read-only source checkout before sharing Backup setup')
                if options.get('path') == 'framework-source':
                    compiler.require(options.get('repository') == framework['repository']
                                     and options.get('ref') == framework['revision'],
                                     'Select the same reviewed framework for PBS policy and Backup CD')
                else:
                    compiler.require(set(options) <= {'persist-credentials', 'ref'}
                                     and options.get('ref', '${{ github.sha }}') == '${{ github.sha }}',
                                     'Keep the existing authored PBS source checkout')
                continue  # The shared immutable Setup already performs these checkouts.
            if step.get('run') == 'python3 -m pip install --require-hashes -r framework-source/requirements.lock.txt':
                compiler.require(set(step) <= {'name', 'run'}, 'Keep finite source tooling installation')
                continue  # Replaced by the existing job-owned, hash-locked Setup.
            compiler.require('/opt/homelab-tools/' not in json.dumps(step)
                             and not step.get('continue-on-error')
                             and not re.search(r'\bsteps\s*\[', json.dumps(step)),
                             'PBS policy must use selected job tools and preserve failures')
            step = bind_steps(step)
            if 'id' in step: step['id'] = identities[original['id']]
            if label == 'host':
                guard = "steps.pbs_check_selection.outputs.selected == 'true'"
                step['if'] = '(' + step['if'] + ') && ' + guard if 'if' in step else 'success() && ' + guard
            result.append(step)
    return result


def model(stack, site):
    env, labels = settings(site)
    validation = validation_workflow(site)
    pbs = pbs_workflow(site, labels)
    selected_source = compiler.workflow_selection(site / '.github/workflows/deploy.yml', 'deploy.yml')
    compiler.check_revision(stack, selected_source['revision'])
    compiler.require(not subprocess.check_output(
        ['git', '-C', str(stack), 'status', '--porcelain', '--untracked-files=all'], text=True).strip(),
        'Use clean pinned stack source for private workflow generation')
    disabled = env.get('HOMELAB_DISABLED', '[]')
    disabled_rows = compiler.workflow_disabled((site / '.github/workflows/deploy.yml').read_text())
    source = workflows.models(stack, site_source=compiler.site_path(site), disabled=disabled_rows)
    compiler.require(not pbs or all(key in ('selection', '_backup') or re.fullmatch('[a-z][a-z0-9_-]*', key)
                                   for key in source['deploy.yml']['jobs']),
                     'Keep only public guest jobs and the early Backup job')
    repository = 'github.repository == ' + repr(env['HOMELAB_REPOSITORY'])
    condition = repository + ' && ' + workflows.PRIVATE_MAIN
    result = {'name': 'Deploy', 'on': {'push': {'branches': ['main']}},
              'permissions': {'contents': 'read'},
              'concurrency': {'group': 'homelab-private-deployment', 'cancel-in-progress': False, 'queue': 'max'},
              'defaults': {'run': {'shell': 'bash'}}, 'env': copy.deepcopy(env),
              'jobs': {'validate': validation}}
    selector = bind(copy.deepcopy(source['deploy.yml']['jobs']['selection']), disabled)
    selector.update(needs=['validate'], **{'if': condition})
    result['jobs']['selection'] = selector
    for guest in source['deploy.yml']['jobs']:
        if guest == 'selection':
            continue
        caller = source['deploy.yml']['jobs'][guest]
        filename = 'backup.yml' if guest == '_backup' else 'guest-' + guest + '.yml'
        job = bind(copy.deepcopy(source[filename]['jobs']['deploy']), disabled)
        job.update(name=caller['name'], needs=copy.deepcopy(caller['needs']),
                   environment='backup' if guest == '_backup' else env['HOMELAB_ENVIRONMENT_PREFIX'] + '-' + guest,
                   **{'runs-on': labels, 'if': repository + ' && ' + caller['if'].replace("inputs.disabled || '[]'", repr(disabled or '[]'))})
        text = json.dumps(job)
        compiler.require(not WORKFLOW_INPUTS.search(text) and 'secrets: inherit' not in text,
                         'Materialize only closed guest workflow inputs')
        names = set(re.findall(r'\bsecrets\.([A-Za-z0-9_]+)', text))
        compiler.require(names <= source[filename]['on']['workflow_call']['secrets'].keys(),
                         'Preserve each guest secret subset')
        result['jobs'][guest] = job
    if pbs:
        framework = compiler.workflow_selection(stack/'.github/workflows/phase.yml', 'guest-phase.yml')
        steps = pbs_steps(pbs, framework)
        if '_backup' not in result['jobs']:
            result['jobs']['_backup'] = {'name': 'Backup', 'needs': ['selection'], 'if': condition,
                'runs-on': labels, 'environment': pbs['jobs']['firewall']['environment'],
                'timeout-minutes': pbs['jobs']['firewall']['timeout-minutes'],
                'steps': [{'name': 'Setup', 'uses': framework['repository'] + '/.github/actions/guest-setup@' + framework['revision']}]}
        backup = result['jobs']['_backup']
        compiler.require(backup['name'] == 'Backup' and backup['needs'] == ['selection']
                         and backup['steps'][0].get('name') == 'Setup',
                         'Keep one early Backup job, never a final guest coordinator')
        backup['environment'] = pbs['jobs']['firewall']['environment']
        backup['timeout-minutes'] = pbs['jobs']['firewall']['timeout-minutes']
        backup['steps'][1:1] = steps
    return result


def rendered(stack, site):
    return HEADER + yaml.safe_dump(model(stack, site), sort_keys=False, width=1000)


def synchronize(stack, site, *, check):
    expected = rendered(stack, site)
    path = site / '.github/workflows/deploy.yml'
    if check:
        compiler.require(path.read_text() == expected, 'Regenerate the exact private guest workflow; do not alter jobs or secret scope')
        return False
    changed = path.read_text() != expected
    if changed:
        path.write_text(expected)
    return changed


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--stack', type=Path, required=True)
    parser.add_argument('--site', type=Path, required=True)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    changed = synchronize(args.stack, args.site, check=args.check)
    print(json.dumps({'private_guest_jobs_materialized': True, 'changed': changed, 'targets_contacted': False}))


if __name__ == '__main__':
    main()
