"""After-install network setup; the live disk guard is separate."""
from pathlib import Path
import os
import shutil
import tempfile

PROFILE = None


def configuration(nics,profile=None):
    p=profile if profile is not None else PROFILE
    if p is None:raise ValueError('No embedded network profile')
    for name,mac in p['expected'].items():
        if nics.get(name)!=mac or list(nics.values()).count(mac)!=1:
            raise ValueError('Missing or ambiguous pinned physical NIC: '+name)
    m,s=p['management'],p['storage']
    return f'''# Generated by the homelab installer first-boot hook.
auto lo
iface lo inet loopback

iface mgmt0 inet manual
iface fast0 inet manual

auto vmbr0
iface vmbr0 inet manual
    bridge-ports mgmt0
    bridge-stp off
    bridge-fd 0
    bridge-vlan-aware yes
    bridge-vids {' '.join(map(str,p['admin_vlans']))}

auto vmbr0.{m['vlan']}
iface vmbr0.{m['vlan']} inet static
    address {m['address']}
    gateway {m['gateway']}

auto vmbr1
iface vmbr1 inet manual
    bridge-ports fast0
    bridge-stp off
    bridge-fd 0
    bridge-vlan-aware yes
    bridge-vids {' '.join(map(str,p['fast_vlans']))}

auto vmbr1.{s['vlan']}
iface vmbr1.{s['vlan']} inet static
    address {s['address']}

source /etc/network/interfaces.d/*
'''


def install(root=Path('/')):
    net=root/'sys/class/net'
    nics={p.name:(p/'address').read_text().strip().lower() for p in net.iterdir() if (p/'address').is_file()}
    rendered=configuration(nics)
    target=root/'etc/network/interfaces';backup=target.with_name('interfaces.before-homelab')
    if target.is_symlink() or not target.is_file() or backup.exists():raise ValueError('Unexpected network configuration or previous hook run')
    with backup.open('xb') as saved:saved.write(target.read_bytes())
    shutil.copystat(target,backup)
    fd,temp=tempfile.mkstemp(prefix='.homelab-',dir=target.parent)
    try:
        with os.fdopen(fd,'w') as stream:stream.write(rendered);stream.flush();os.fsync(stream.fileno())
        os.chmod(temp,0o644);os.replace(temp,target)
    finally:
        if os.path.exists(temp):os.unlink(temp)


if __name__=='__main__':install()
